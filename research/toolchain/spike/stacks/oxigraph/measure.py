"""Stack A measurement on the generated 500-page vault.

Usage: uv run --locked python stacks/oxigraph/measure.py [RUNS]   (default 7 runs per cell; first = cold)
Cold = first run in this process (fresh interpreter, first query use); warm = runs 2..N.
Vault files are written just before timing, so they are in the OS file cache for all runs.
"""
import os
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import pyoxigraph

SPIKE = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(SPIKE))
import gen_vault  # noqa: E402

from checks import run_check  # noqa: E402
from loader import build_store, parse, load_vault  # noqa: E402

RUNS = int(sys.argv[1]) if len(sys.argv) > 1 else 7
THRESH = {"local": 1.0, "neighborhood": 2.0, "full": 5.0}


def sh(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def machine():
    print("## Machine")
    print(f"- CPU: {sh(['sysctl', '-n', 'machdep.cpu.brand_string'])} ({os.cpu_count()} logical cores)")
    print(f"- RAM: {int(sh(['sysctl', '-n', 'hw.memsize'])) / 2**30:.0f} GiB")
    print(f"- OS: {platform.platform()}")
    print(f"- Python: {platform.python_version()} ({platform.python_implementation()})")
    print(f"- pyoxigraph: {pyoxigraph.__version__}")


def timed(fn, runs=RUNS):
    ts, res = [], None
    for _ in range(runs):
        t = time.perf_counter()
        res = fn()
        ts.append(time.perf_counter() - t)
    return ts, res


def cell(ts):
    w = ts[1:]
    return (f"{ts[0]:.3f}", f"{statistics.median(w):.3f}", f"{min(w):.3f}", f"{max(w):.3f}")


def main():
    tmp = tempfile.mkdtemp(prefix="scpt-vault-500-")
    gen_vault.main(tmp)
    n = len(list(Path(tmp).glob("*.md")))
    machine()
    print(f"\n## Vault\n- {n} pages generated by gen_vault.py into a temp dir; runs per cell: {RUNS} (cold = run 1, warm = runs 2..{RUNS})")

    pages = parse(tmp)
    store = build_store(pages)
    deg = {}
    for r in store.query("PREFIX sp: <https://example.org/scpt-spike#> SELECT ?s (COUNT(?o) AS ?c) WHERE "
                         "{ { ?s sp:linksTo ?o } UNION { ?o sp:linksTo ?s } } GROUP BY ?s"):
        deg[r["s"].value] = int(r["c"].value)
    from loader import BASE
    from urllib.parse import unquote
    hub = unquote(max(deg, key=lambda k: (deg[k], k))[len(BASE):])
    print(f"- page used for local/neighborhood: '{hub}' (highest link degree, {max(deg.values())}; worst case)")

    ps, _ = timed(lambda: parse(tmp))
    bs, _ = timed(lambda: build_store(pages))
    ls, _ = timed(lambda: load_vault(tmp))
    print("\n## Timings (seconds)\n")
    print("| what is timed | cold | warm median | warm min | warm max | threshold | verdict (warm median) |")
    print("|---|---|---|---|---|---|---|")
    for label, ts in (("load: parse files only (common.parse_vault)", ps),
                      ("load: build RDF store from parsed pages", bs),
                      ("load: parse + build (whole vault)", ls)):
        print(f"| {label} | " + " | ".join(cell(ts)) + " | - | - |")
    results = {}
    for scope in ("local", "neighborhood", "full"):
        ts, msgs = timed(lambda s=scope: run_check(store, s, hub))
        assert msgs == [], msgs
        results[scope] = ts
        c = cell(ts)
        v = "PASS" if statistics.median(ts[1:]) < THRESH[scope] else "FAIL"
        print(f"| {scope}: query only (store prebuilt) | " + " | ".join(c) + f" | < {THRESH[scope]:g} s | {v} |")
    for scope in ("local", "neighborhood", "full"):
        def e2e(s=scope):
            st, *_ = load_vault(tmp)
            return run_check(st, s, hub)
        ts, msgs = timed(e2e)
        assert msgs == []
        c = cell(ts)
        v = "PASS" if statistics.median(ts[1:]) < THRESH[scope] else "FAIL"
        print(f"| {scope}: load + query (end to end) | " + " | ".join(c) + f" | < {THRESH[scope]:g} s | {v} |")
    print("\nAll checks returned 0 violations on the clean synthetic vault.")


if __name__ == "__main__":
    main()
