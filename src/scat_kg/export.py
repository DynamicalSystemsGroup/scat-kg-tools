"""Exports (M6): each edge table written as CSV and as a generated Markdown document, only when called (R-4).

    scat_kg.export_edges("tables")      # tables/holds.csv, tables/holds.md, and the same for the other two types

The data is the view's (`edge_table`), so an export refuses where the view refuses and then writes nothing. A file
that exists is rewritten only when its content differs; repeating the call changes nothing. Names are plain text,
never `[[links]]`, so an export made a page, a link or a row in no vault. An uncoded narrative is excluded, as in
the view, and the result carries a note for each.
"""

import csv
import dataclasses
import io
from pathlib import Path

from scat_kg.ops.common import open_vault
from scat_kg.ops.files import replace_file
from scat_kg.ops.result import Refusal, Result, reports_mode
from scat_kg.tbox import TBOX
from scat_kg.views import View, edge_table

OPERATION = "export-edges"


def _csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["from", "to", "narratives", "status"])
    for r in rows:
        w.writerow([r["from"], r["to"], ";".join(r["narratives"]), r["status"]])
    return buf.getvalue()


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _markdown(d: dict) -> str:
    slug = d["edge_type"]
    lines = [
        f"# Edges: {slug}",
        "",
        (
            f"The edges of type `{slug}`, from {d['from_layer']} to {d['to_layer']}, as the narratives "
            "tell them. Generated by `scat export-edges`; do not edit."
        ),
        "",
        "| from | to | narratives | status |",
        "|---|---|---|---|",
    ]
    for r in d["rows"]:
        told = "; ".join(r["narratives"])
        lines.append(f"| {_cell(r['from'])} | {_cell(r['to'])} | {_cell(told)} | {r['status']} |")
    return "\n".join(lines) + "\n"


def _shown(out: Path, name: str, vault_root: Path) -> str:
    """The path in the Result: vault-relative with `/` inside the vault, else as given."""
    try:
        return (out / name).resolve().relative_to(vault_root.resolve()).as_posix()
    except ValueError:
        return (out / name).as_posix()


@reports_mode
def export_edges(out: str | Path, *, root: str | Path = ".") -> Result:
    """Write each edge type's table to `<out>/<slug>.csv` and `<out>/<slug>.md`."""
    vault, bad = open_vault(OPERATION, root)
    if bad:
        return bad
    out = Path(out)
    files: list[tuple[str, str]] = []
    notes: tuple[str, ...] = ()
    for slug in TBOX.edge_types:
        view = edge_table(slug, root=root)
        if not isinstance(view, View):
            return dataclasses.replace(view, operation=OPERATION)
        notes = tuple(
            f"excluded {x['name']} ({x['file']}): it links no node page, so no table has its edges; "
            "link one node page in it to include it"
            for x in view.data["excluded"]
        )
        files += [(f"{slug}.csv", _csv(view.data["rows"])), (f"{slug}.md", _markdown(view.data))]
    if out.exists() and not out.is_dir():
        return Result(
            OPERATION,
            refused=(
                Refusal(
                    out.as_posix(),
                    "a file has the name of the folder the tables go in",
                    f"give another folder with `--out`, or rename or move `{out.as_posix()}`",
                ),
            ),
        )
    created, changed, unchanged = [], [], []
    try:
        out.mkdir(parents=True, exist_ok=True)
        for name, text in files:
            path, data = out / name, text.encode("utf-8")
            shown = _shown(out, name, vault.root)
            if path.is_dir():
                raise IsADirectoryError(f"{shown} is a folder")
            if not path.exists():
                path.write_bytes(data)
                created.append(shown)
            elif path.read_bytes() == data:
                unchanged.append(shown)
            else:
                replace_file(path, data)
                changed.append(shown)
    except OSError as e:
        return Result(
            OPERATION,
            created=tuple(created),
            changed=tuple(changed),
            unchanged=tuple(unchanged),
            notes=notes,
            refused=(
                Refusal(out.as_posix(), f"could not write: {e}", "check the folder's permissions"),
            ),
        )
    return Result(
        OPERATION,
        created=tuple(created),
        changed=tuple(changed),
        unchanged=tuple(unchanged),
        notes=notes,
    )
